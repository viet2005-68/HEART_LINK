-- Heartlink Phase 2 baseline schema (Flyway V1)
-- Canonical PostgreSQL 16 schema aligned with the 6 JPA entities:
--   users, refresh_tokens, swipes, matches, messages, notifications
-- Upgrade contract:
--   * Fresh databases migrate cleanly from V1 onwards.
--   * Existing non-empty databases MUST NOT enable baseline-on-migrate blindly;
--     audit live metadata against V1 before an explicit manual baseline at version 1.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name          VARCHAR(100) NOT NULL,
    bio           TEXT,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id    BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT refresh_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE swipes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    swiper_id  BIGINT NOT NULL,
    target_id  BIGINT NOT NULL,
    action     VARCHAR(10) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT swipes_pkey PRIMARY KEY (id),
    CONSTRAINT uq_swipe_pair UNIQUE (swiper_id, target_id),
    CONSTRAINT swipes_action_check CHECK (action IN ('LIKE', 'PASS')),
    CONSTRAINT fk_swipes_swiper FOREIGN KEY (swiper_id) REFERENCES users (id),
    CONSTRAINT fk_swipes_target FOREIGN KEY (target_id) REFERENCES users (id)
);

CREATE TABLE matches (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_a_id    BIGINT NOT NULL,
    user_b_id    BIGINT NOT NULL,
    status       VARCHAR(10) NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cancelled_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT matches_pkey PRIMARY KEY (id),
    CONSTRAINT uq_match_pair UNIQUE (user_a_id, user_b_id),
    CONSTRAINT matches_status_check CHECK (status IN ('ACTIVE', 'CANCELLED')),
    CONSTRAINT fk_matches_user_a FOREIGN KEY (user_a_id) REFERENCES users (id),
    CONSTRAINT fk_matches_user_b FOREIGN KEY (user_b_id) REFERENCES users (id)
);

CREATE INDEX idx_matches_user_a_status_created
    ON matches (user_a_id, status, created_at);

CREATE INDEX idx_matches_user_b_status_created
    ON matches (user_b_id, status, created_at);

CREATE TABLE messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    match_id   BIGINT NOT NULL,
    sender_id  BIGINT NOT NULL,
    content    VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT messages_pkey PRIMARY KEY (id),
    CONSTRAINT fk_messages_match FOREIGN KEY (match_id) REFERENCES matches (id),
    CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id) REFERENCES users (id)
);

CREATE INDEX idx_messages_match_id
    ON messages (match_id, id);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id    BIGINT NOT NULL,
    match_id   BIGINT NOT NULL,
    type       VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT notifications_pkey PRIMARY KEY (id),
    CONSTRAINT uq_notification_user_match_type UNIQUE (user_id, match_id, type),
    CONSTRAINT notifications_type_check CHECK (type IN ('MATCH_CREATED')),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_match FOREIGN KEY (match_id) REFERENCES matches (id)
);

CREATE INDEX idx_notifications_user_id
    ON notifications (user_id, id);

